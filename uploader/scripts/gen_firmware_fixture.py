"""Regenerate firmware/test/test_core/fixture.h from the uploader's encoder.

The firmware unit tests decode these chunks with codec::base64Decode and check
size/CRC/markers, so a change on either side of the wire format that breaks
compatibility fails CI.

    python uploader/scripts/gen_firmware_fixture.py
"""

from __future__ import annotations

import io
from pathlib import Path

from PIL import Image

from instascreen_uploader.encode import encode, prepare_jpeg

OUT = Path(__file__).resolve().parents[2] / "firmware/test/test_core/fixture.h"


def main() -> None:
    img = Image.linear_gradient("L").resize((64, 48)).convert("RGB")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    enc = encode(prepare_jpeg(buf, size=(64, 48)), chunk_bytes=256)
    m = enc.meta
    chunks = ",\n".join(f'    "\\"{c}\\""' for c in enc.chunks)  # JSON-quoted, as RTDB returns
    hex_chunks = ",\n".join(
        f'    "\\"{enc.jpeg[i : i + 256].hex().upper()}\\""' for i in range(0, len(enc.jpeg), 256)
    )
    OUT.write_text(
        "// GENERATED by uploader/scripts/gen_firmware_fixture.py - do not edit.\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
        "namespace fixture {\n"
        f"constexpr uint32_t kSize = {m['size']};\n"
        f"constexpr uint32_t kCrc32 = 0x{m['crc32']:08X}u;\n"
        f"constexpr size_t kChunkCount = {m['chunk_count']};\n"
        f"static const char* const kBase64Chunks[] = {{\n{chunks}\n}};\n"
        f"static const char* const kHexChunks[] = {{\n{hex_chunks}\n}};\n"
        "}  // namespace fixture\n"
    )
    print(f"wrote {OUT} ({m['size']} bytes, {m['chunk_count']} chunks)")


if __name__ == "__main__":
    main()
